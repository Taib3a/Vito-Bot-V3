/** المفاتيح مرتّبة من الأطول إلى الأقصر حتى لا يبتلع مفتاح قصير عبارة أطول. */
const CLAVES = Object.keys(TRADUCCIONES).sort((a, b) => b.length - a.length);

/**
 * يترجم رسالة إسبانية إلى العربية.
 * @param {string} text
 * @returns {string}
 */
export function traducir(text) {
  if (typeof text !== "string" || !text) return text;
  let out = text;
  for (const es of CLAVES) {
    if (out.includes(es)) out = out.split(es).join(TRADUCCIONES[es]);
  }
  return out;
}

/**
 * يترجم أي شكل من أشكال محتوى الرد: نص، كائن فيه text، أو كائن فيه caption.
 * يعدّل نسخة ولا يمسّ الأصل.
 */
export function traducirContenido(content) {
  if (typeof content === "string") return traducir(content);
  if (!content || typeof content !== "object") return content;

  const copia = { ...content };
  if (typeof copia.text === "string") copia.text = traducir(copia.text);
  if (typeof copia.caption === "string") copia.caption = traducir(copia.caption);
  return copia;
}
