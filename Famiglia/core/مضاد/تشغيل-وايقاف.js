import { db } from "../../database/db.js";

// أمر «تشغيل/إيقاف البوت في المجموعة»: وحدة في قسم المضادات تُسجَّل تلقائياً.
// يظهر في لوحة رقم البوت وحده، وإعداده لكل (رقم + مجموعة): رقم واحد قد يتوقف
// في مجموعة ويبقى يعمل في غيرها.
// رقم البوت لا يستطيع ضغط الأزرار، فلوحته نصّية وتُرشده إلى الأمر الذي يكتبه.
export default {
  name: "تشغيل-وايقاف",
  flag: "botOn",
  mode: "bot",

  /** سطر الحالة داخل اللوحة. */
  status: (on) => `• البوت في المجموعة: ${on ? "يعمل 🟢" : "متوقف 🔴"}`,

  /** الأمر الذي يكتبه رقم البوت للتبديل. */
  hint: (on) => (on ? "> لإيقاف البوت اكتب: *ايقاف*" : "> لتشغيل البوت اكتب: *تشغيل*"),

  /** أوامر التبديل التي يكتبها رقم البوت، لأن الأزرار لا تعمل معه. */
  commands: { تشغيل: true, ايقاف: false, "إيقاف": false },

  /** on=true تشغيل، on=false إيقاف. يعيد نصّ التأكيد وما إذا تغيّرت الحالة. */
  async run({ from, on, botNum }) {
    const cur = !!db.getBotGroup(botNum, from).botOn;

    if (on === cur) {
      return { changed: false, text: on ? "🟢 البوت يعمل بالفعل في هذه المجموعة." : "🔴 البوت متوقف بالفعل في هذه المجموعة." };
    }

    db.setBotGroup(botNum, from, { botOn: on });
    return {
      changed: true,
      text: on
        ? "🟢 *تم تشغيل البوت في هذه المجموعة.*\n> عاد يستجيب للأوامر والرسائل."
        : "🔴 *تم إيقاف البوت في هذه المجموعة.*\n> لن يستجيب لأي أمر حتى تشغّله مجدداً.",
    };
  },
};
