import { db } from "../../database/db.js";

// أمر «تشغيل/إيقاف البوت في المجموعة»: وحدة في قسم المضادات تُسجَّل تلقائياً.
// يظهر في لوحة رقم البوت وحده، فلا يتحكم به مشرفو المجموعة.
export default {
  name: "تشغيل-وايقاف",
  flag: "botoff",
  mode: "bot",

  /** سطر الحالة داخل اللوحة. */
  status: (off) => `• البوت في المجموعة: ${off ? "متوقف 🔴" : "يعمل 🟢"}`,

  /** زرّ التبديل: إيقاف حين يعمل، وتشغيل حين يتوقف. */
  button: (off) => ({
    text: off ? "🟢 تشغيل البوت" : "🔴 إيقاف البوت",
    id: off ? ".تفعيل_botoff" : ".تعطيل_botoff",
  }),

  /** on=true تشغيل، on=false إيقاف. يعيد نصّ التأكيد وما إذا تغيّرت الحالة. */
  async run({ from, on }) {
    const off = !!db.getGroup(from)?.botOff;

    if (!on && off) return { changed: false, text: "🔴 البوت متوقف بالفعل في هذه المجموعة." };
    if (on && !off) return { changed: false, text: "🟢 البوت يعمل بالفعل في هذه المجموعة." };

    db.setGroup(from, { botOff: !on });
    return {
      changed: true,
      text: on
        ? "🟢 *تم تشغيل البوت في هذه المجموعة.*\n> عاد يستجيب للأوامر والرسائل."
        : "🔴 *تم إيقاف البوت في هذه المجموعة.*\n> لن يستجيب لأي أمر حتى تكتب *تفعيل* مجدداً.",
    };
  },
};
